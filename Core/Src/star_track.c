static int px_luma_chroma(uint16_t p, int *chroma)
{
  int r = (int)((p >> 11) & 31U);
  int g = (int)((p >> 5) & 63U);
  int b = (int)(p & 31U);
  int mx, mn;
  r = (r << 3) | (r >> 2);
  g = (g << 2) | (g >> 4);
  b = (b << 3) | (b >> 2);
  mx = r; if (g > mx) { mx = g; } if (b > mx) { mx = b; }
  mn = r; if (g < mn) { mn = g; } if (b < mn) { mn = b; }
  *chroma = mx - mn;
  return ((r * 77) + (g * 150) + (b * 29)) >> 8;
}

/* 以 (cx,cy) 为中心每 2° 向外找候选像素最远半径（降采样像素，×1）。 */
static void cast_rays(const uint8_t *cmap, int W, int H, uint8_t id, float cx, float cy,
                      float rmax, float *rr)
{
  int k;
  for (k = 0; k < 180; k++)
  {
    float c = s_c360[k * 2];
    float s = s_s360[k * 2];
    float r;
    float best = 0.0f;
    for (r = 1.0f; r <= rmax; r += 0.5f)
    {
      int x = (int)(cx + (r * c) + 0.5f);
      int y = (int)(cy + (r * s) + 0.5f);
      if ((x < 0) || (y < 0) || (x >= W) || (y >= H)) { break; }
      if (cmap[(y * W) + x] == id) { best = r; }
    }
    rr[k] = best;
  }
}

static void sort_f(float *a, int n)
{
  int i, j;
  for (i = 1; i < n; i++)
  {
    float v = a[i];
    j = i - 1;
    while ((j >= 0) && (a[j] > v)) { a[j + 1] = a[j]; j--; }
    a[j + 1] = v;
  }
}

/* Kasa 圆拟合：x²+y²+Dx+Ey+F=0 */
static int fit_circle_f(const float *xs, const float *ys, int n, float *ocx, float *ocy, float *orad)
{
  double sx = 0, sy = 0, sxx = 0, syy = 0, sxy = 0, sz = 0, sxz = 0, syz = 0;
  double a[3][4];
  int i, r, c, k;
  if (n < 6) { return -1; }
  for (i = 0; i < n; i++)
  {
    double x = xs[i], y = ys[i], z = (x * x) + (y * y);
    sx += x; sy += y; sxx += x * x; syy += y * y; sxy += x * y;
    sz += z; sxz += x * z; syz += y * z;
  }
  a[0][0] = sxx; a[0][1] = sxy; a[0][2] = sx; a[0][3] = -sxz;
  a[1][0] = sxy; a[1][1] = syy; a[1][2] = sy; a[1][3] = -syz;
  a[2][0] = sx;  a[2][1] = sy;  a[2][2] = n;  a[2][3] = -sz;
  for (c = 0; c < 3; c++)
  {
    int piv = c;
    for (r = c + 1; r < 3; r++) { if (fabs(a[r][c]) > fabs(a[piv][c])) { piv = r; } }
    if (fabs(a[piv][c]) < 1e-9) { return -1; }
    if (piv != c) { for (k = 0; k < 4; k++) { double t = a[c][k]; a[c][k] = a[piv][k]; a[piv][k] = t; } }
    for (r = 0; r < 3; r++)
    {
      double f;
      if (r == c) { continue; }
      f = a[r][c] / a[c][c];
      for (k = c; k < 4; k++) { a[r][k] -= f * a[c][k]; }
    }
  }
  {
    double D = a[0][3] / a[0][0], E = a[1][3] / a[1][1], F = a[2][3] / a[2][2];
    double cx = -D / 2.0, cy = -E / 2.0, rr = (cx * cx) + (cy * cy) - F;
    if (rr <= 1.0) { return -1; }
    *ocx = (float)cx; *ocy = (float)cy; *orad = (float)sqrt(rr);
  }
  return 0;
}

typedef struct
{
  float cx, cy, r_out, r_in, score;
  int n, trans;
} eval_t;

static int eval_cand(const uint8_t *cmap, int W, int H, uint8_t id, const cand_t *cd, eval_t *ev)
{
  static float rr[180];
  static float srt[180];
  static float px[180];
  static float py[180];
  float cx = 0.5f * (float)(cd->minx + cd->maxx);
  float cy = 0.5f * (float)(cd->miny + cd->maxy);
  float R0 = 0.5f * (float)(((cd->maxx - cd->minx) > (cd->maxy - cd->miny)) ?
                            (cd->maxx - cd->minx) : (cd->maxy - cd->miny));
  float R = R0, rin, rp, mean;
  int it, k, n, bestn = 0, trans = 0;
  float best = 0.0f;
  uint8_t prof[360];

  for (it = 0; it < 3; it++)
  {
    float thr;
    cast_rays(cmap, W, H, id, cx, cy, R0 * 1.4f + 2.0f, rr);
    memcpy(srt, rr, sizeof(srt));
    sort_f(srt, 180);
    thr = srt[179] * 0.86f;
    n = 0;
    for (k = 0; k < 180; k++)
    {
      if (rr[k] >= thr)
      {
        px[n] = cx + (rr[k] * s_c360[k * 2]);
        py[n] = cy + (rr[k] * s_s360[k * 2]);
        n++;
      }
    }
    {
      float ncx, ncy, nr;
      if (fit_circle_f(px, py, n, &ncx, &ncy, &nr) != 0) { return -1; }
      if ((fabsf(ncx - cx) > R0) || (fabsf(ncy - cy) > R0)) { return -1; }
      cx = ncx; cy = ncy; R = nr;
    }
  }
  cast_rays(cmap, W, H, id, cx, cy, R * 1.3f + 2.0f, rr);
  for (k = 0; k < 180; k++) { g_star_rmax[k] = (uint16_t)(rr[k] * 4.0f); }
  memcpy(srt, rr, sizeof(srt));
  sort_f(srt, 180);
  rin = srt[18];
  if ((R < 8.0f) || (rin > (0.92f * R))) { return -1; }
  rp = 0.5f * (rin + R);
  mean = 0.0f;
  for (k = 0; k < 360; k++)
  {
    int x = (int)(cx + (rp * s_c360[k]) + 0.5f);
    int y = (int)(cy + (rp * s_s360[k]) + 0.5f);
    uint8_t v = 0U;
    if ((x >= 0) && (y >= 0) && (x < W) && (y < H) && (cmap[(y * W) + x] == id)) { v = 1U; }
    prof[k] = v;
    mean += (float)v;
  }
  mean /= 360.0f;
  for (k = 0; k < 360; k++)
  {
    if ((prof[k] == 1U) && (prof[(k + 1) % 360] == 0U)) { trans++; }
  }
  for (n = 3; n <= 12; n++)
  {
    float c = 0.0f, s = 0.0f, mag;
    for (k = 0; k < 360; k++)
    {
      float v = (float)prof[k] - mean;
      int a = (n * k) % 360;
      c += v * s_c360[a];
      s += v * s_s360[a];
    }
    mag = 2.0f * sqrtf((c * c) + (s * s)) / 360.0f;
    if (mag > best) { best = mag; bestn = n; }
  }
  ev->cx = cx; ev->cy = cy; ev->r_out = R; ev->r_in = rin;
  ev->n = bestn; ev->trans = trans; ev->score = best;
  if (best < 0.25f) { return -1; }
  if ((trans != bestn) && (best < 0.40f)) { return -1; }
  return 0;
}

/* 在原图亮度上按半径扫 N 次谐波幅度，采样圆环放在齿/缺口明暗交替最强的那一段。 */
uint16_t g_star_rad_amp[STAR_RAD_MAX];   /* 每个半径（原图像素）的 N 次谐波幅度 ×10 */
uint16_t g_star_rad_n;

static int pick_annulus(const uint16_t *rgb, uint16_t stride, int w, int h,
                        float cx, float cy, int n, float r_out, int *o_r0, int *o_r1, int *o_rpk)
{
  int ra = (int)(0.45f * r_out), rb = (int)(1.35f * r_out) + 2;
  int r, k, rpk = -1, r0, r1;
  float amax = 0.0f;
  static float amp[STAR_RAD_MAX];
  if (ra < 3) { ra = 3; }
  if (rb >= (int)STAR_RAD_MAX) { rb = (int)STAR_RAD_MAX - 1; }
  g_star_rad_n = 0U;
  if ((n < 3) || (rb <= ra)) { return -1; }
  for (r = 0; r < (int)STAR_RAD_MAX; r++) { amp[r] = 0.0f; g_star_rad_amp[r] = 0U; }
  for (r = ra; r <= rb; r++)
  {
    float c = 0.0f, s = 0.0f, m = 0.0f;
    int cnt = 0, out = 0;
    for (k = 0; k < 360; k++)
    {
      int x = (int)(cx + ((float)r * s_c360[k]) + 0.5f);
      int y = (int)(cy + ((float)r * s_s360[k]) + 0.5f);
      int ch, Y, a;
      if ((x < 0) || (y < 0) || (x >= w) || (y >= h)) { out++; continue; }
      Y = px_luma_chroma(rgb[((uint32_t)y * stride) + (uint32_t)x], &ch);
      a = (n * k) % 360;
      c += (float)Y * s_c360[a];
      s += (float)Y * s_s360[a];
      m += (float)Y;
      cnt++;
    }
    if ((out > 18) || (cnt == 0)) { continue; }   /* 圆出了画面就不用 */
    (void)m;
    amp[r] = 2.0f * sqrtf((c * c) + (s * s)) / (float)cnt;
    g_star_rad_amp[r] = (uint16_t)(amp[r] * 10.0f);
    if (amp[r] > amax) { amax = amp[r]; rpk = r; }
  }
  g_star_rad_n = (uint16_t)(rb + 1);
  if ((rpk < 0) || (amax < 12.0f)) { return -1; }
  r0 = rpk; r1 = rpk;
  while ((r0 > ra) && (amp[r0 - 1] >= (0.6f * amax))) { r0--; }
  while ((r1 < rb) && (amp[r1 + 1] >= (0.6f * amax))) { r1++; }
  /* 边上留 1 像素，保证至少 6 像素宽 */
  if ((r1 - r0) > 8) { r0++; r1--; }
  while ((r1 - r0) < 6) { if (r0 > ra) { r0--; } if (r1 < rb) { r1++; } if ((r0 <= ra) && (r1 >= rb)) { break; } }
  *o_r0 = r0; *o_r1 = r1; *o_rpk = rpk;
  return 0;
}

static int locate_once(const uint16_t *rgb, uint16_t stride, uint16_t w, uint16_t h, uint8_t ds,
                       uint8_t *work, uint32_t work_bytes, uint16_t skip_x1, uint16_t skip_y1, int tmode);

uint8_t g_star_tmode;   /* 最近一次定位成功用的阈值：1=暗峰-中位数插值，0=中位数×55% */

int StarTrack_Locate(const uint16_t *rgb, uint16_t stride, uint16_t w, uint16_t h, uint8_t ds,
                     uint8_t *work, uint32_t work_bytes, uint16_t skip_x1, uint16_t skip_y1)
{
  if (locate_once(rgb, stride, w, h, ds, work, work_bytes, skip_x1, skip_y1, 1) == 0)
  {
    g_star_tmode = 1U;
    return 0;
  }
  if (locate_once(rgb, stride, w, h, ds, work, work_bytes, skip_x1, skip_y1, 0) == 0)
  {
    g_star_tmode = 0U;
    return 0;
  }
  return -1;
}

static int locate_once(const uint16_t *rgb, uint16_t stride, uint16_t w, uint16_t h, uint8_t ds,
                       uint8_t *work, uint32_t work_bytes, uint16_t skip_x1, uint16_t skip_y1, int tmode)
{
  int W, H, x, y, i;
  uint8_t *mask;
  uint8_t *cmap;
  uint32_t *queue;
  uint32_t hist[256];
  uint32_t tot = 0U, acc = 0U;
  int med = 128, T;
  cand_t cands[MAX_CAND];
  int nc = 0;
  eval_t best_ev;
  int best_i = -1;

  if ((rgb == 0) || (work == 0) || (ds < 1U)) { return -1; }
  trig_init();
  W = (int)w / (int)ds;
  H = (int)h / (int)ds;
  if ((W < 16) || (H < 16)) { return -1; }
  if (((uint32_t)W * (uint32_t)H * 6U) > work_bytes) { return -1; }
  mask = work;
  cmap = work + ((uint32_t)W * (uint32_t)H);
  queue = (uint32_t *)(void *)(work + (((((uint32_t)W * (uint32_t)H * 2U) + 7U) / 8U) * 8U));

  memset(hist, 0, sizeof(hist));
  for (y = 0; y < H; y++)
  {
    const uint16_t *row = rgb + ((uint32_t)(y * (int)ds) * stride);
    for (x = 0; x < W; x++)
    {
      int ch;
      int Y = px_luma_chroma(row[x * (int)ds], &ch);
      uint8_t *m = &mask[(y * W) + x];
      int skip = (((x * (int)ds) < (int)skip_x1) && ((y * (int)ds) < (int)skip_y1)) ? 1 : 0;
      *m = (uint8_t)Y;
      cmap[(y * W) + x] = (uint8_t)((skip != 0) ? 1U : ((ch < CHROMA_MAX) ? 0U : 2U));
      if (skip == 0) { hist[Y]++; tot++; }
    }
  }
  for (i = 0; i < 256; i++)
  {
    acc += hist[i];
    if ((acc * 2U) >= tot) { med = i; break; }
  }
  T = (med * DARK_PCT) / 100;
  {
    /* Otsu 双峰阈值：小窗里轮子占比大，中位数×55% 会落在轮面亮度里（齿被切掉）。 */
    /* 暗峰（第 5 百分位）与中位数之间取 STAR_T_FRAC，比固定 55% 更贴近轮面与背景的分界。 */
    uint32_t a5 = 0U;
    int p5 = 0, To;
    for (i = 0; i < 256; i++)
    {
      a5 += hist[i];
      if ((a5 * 20U) >= tot) { p5 = i; break; }
    }
    To = p5 + (((med - p5) * STAR_T_FRAC) / 100);
    if ((tmode != 0) && (To > T)) { T = To; }
  }
  if (T < 30) { T = 30; }
  if (T > 180) { T = 180; }
  g_star.med = (uint16_t)med;
  g_star.thr = (uint16_t)T;
  /* mask: 1 = 暗且低饱和、未访问；0 = 其它 */
  for (i = 0; i < (W * H); i++)
  {
    uint8_t v = (uint8_t)(((int)mask[i] < T) && (cmap[i] == 0U));
    mask[i] = v;
    cmap[i] = 0U;
  }
  /* 连通域：广度优先，队列里留着本域像素，合格的写进 cmap（候选号 1..24） */
  for (y = 0; y < H; y++)
  {
    for (x = 0; x < W; x++)
    {
      uint32_t qh = 0U, qt = 0U;
      cand_t cd;
      int edge = 0;
      int bw, bh, dfull;
      if (mask[(y * W) + x] != 1U) { continue; }
      mask[(y * W) + x] = 2U;
      queue[qt++] = ((uint32_t)y << 16) | (uint32_t)x;
      cd.area = 0; cd.minx = (int16_t)x; cd.maxx = (int16_t)x; cd.miny = (int16_t)y; cd.maxy = (int16_t)y;
      while (qh < qt)
      {
        uint32_t e = queue[qh++];
        int ex = (int)(e & 0xFFFFU), ey = (int)(e >> 16);
        int nb;
        cd.area++;
        if (ex < cd.minx) { cd.minx = (int16_t)ex; }
        if (ex > cd.maxx) { cd.maxx = (int16_t)ex; }
        if (ey < cd.miny) { cd.miny = (int16_t)ey; }
        if (ey > cd.maxy) { cd.maxy = (int16_t)ey; }
        if ((ex == 0) || (ey == 0) || (ex == (W - 1)) || (ey == (H - 1))) { edge = 1; }
        for (nb = 0; nb < 4; nb++)
        {
          int nx = ex, ny = ey;
          if (nb == 0) { nx++; } else if (nb == 1) { nx--; } else if (nb == 2) { ny++; } else { ny--; }
          if ((nx < 0) || (ny < 0) || (nx >= W) || (ny >= H)) { continue; }
          if (mask[(ny * W) + nx] == 1U)
          {
            mask[(ny * W) + nx] = 2U;
            queue[qt++] = ((uint32_t)ny << 16) | (uint32_t)nx;
          }
        }
      }
      bw = cd.maxx - cd.minx + 1;
      bh = cd.maxy - cd.miny + 1;
      dfull = ((bw > bh) ? bw : bh) * (int)ds;
      if (edge != 0) { continue; }
      if ((dfull < 50) || (dfull > 320)) { continue; }
      if (((bw * 4) < (bh * 3)) || ((bh * 4) < (bw * 3))) { continue; }
      if (((cd.area * 100) < (bw * bh * FILL_MIN)) || ((cd.area * 100) > (bw * bh * 85))) { continue; }
      if (nc >= MAX_CAND) { continue; }
      cands[nc] = cd;
      nc++;
      for (qh = 0U; qh < qt; qh++)
      {
        uint32_t e = queue[qh];
        cmap[((int)(e >> 16) * W) + (int)(e & 0xFFFFU)] = (uint8_t)nc;
      }
    }
  }
  g_star.ncand = (uint8_t)nc;
  for (i = 0; i < nc; i++)
  {
    eval_t ev;
    if (eval_cand(cmap, W, H, (uint8_t)(i + 1), &cands[i], &ev) != 0) { continue; }
    if ((best_i < 0) || (ev.score > best_ev.score)) { best_ev = ev; best_i = i; }
  }
  if (best_i < 0)
  {
    g_star.found = 0U;
    return -1;
  }
  {
    float f = (float)ds;
    float off = 0.5f * (f - 1.0f);
    g_star.cx = (int16_t)((best_ev.cx * f) + off + 0.5f);
    g_star.cy = (int16_t)((best_ev.cy * f) + off + 0.5f);
    g_star.r_out = (int16_t)((best_ev.r_out * f) + 0.5f);
    g_star.r_in = (int16_t)((best_ev.r_in * f) + 0.5f);
    g_star.n_teeth = (uint8_t)best_ev.n;
    g_star.trans = (uint16_t)best_ev.trans;
    g_star.score_e3 = (uint16_t)(best_ev.score * 1000.0f);
    g_star.ann_r0 = 0;
    g_star.ann_r1 = 0;
    g_star.ann_pk = 0;
    {
      int a0 = 0, a1 = 0, apk = 0;
      if (pick_annulus(rgb, stride, (int)w, (int)h, (best_ev.cx * f) + off, (best_ev.cy * f) + off,
                       best_ev.n, best_ev.r_out * f, &a0, &a1, &apk) != 0)
      {
        g_star.found = 0U;
        return -1;
      }
      g_star.ann_r0 = (int16_t)a0;
      g_star.ann_r1 = (int16_t)a1;
      g_star.ann_pk = (int16_t)apk;
      if (a1 > g_star.r_out) { g_star.r_out = (int16_t)a1; }
    }
    g_star.found = 1U;
  }
  return 0;
}

/* ======================= 行中断采样 ======================= */

void StarTrack_Disarm(void)
{
  s_tab_on = 0U;
  g_star.armed = 0U;
}

int StarTrack_Arm(uint16_t cap_w, uint16_t cap_h)
{
  int cx = g_star.cx, cy = g_star.cy;
  float ro = (float)g_star.r_out, ri = (float)g_star.r_in;
  float r0 = ri + (0.15f * (ro - ri));
  float r1 = ro - (0.12f * (ro - ri));
  if ((g_star.ann_r1 > g_star.ann_r0) && (g_star.ann_r0 > 0))
  {
    /* 定位时按亮度径向扫描选好的齿带 */
    r0 = (float)g_star.ann_r0;
    r1 = (float)g_star.ann_r1 + 0.5f;
  }
  int y0, y1, x, y, k, step = 1, pass;
  uint32_t n = 0U;
  uint32_t cnt[STAR_BINS];
  StarTrack_Disarm();
  if ((g_star.found == 0U) || (g_star.n_teeth < 3U) || ((r1 - r0) < 2.0f)) { return -1; }
  y0 = cy - (int)r1 - 1; if (y0 < 0) { y0 = 0; }
  y1 = cy + (int)r1 + 2; if (y1 > (int)cap_h) { y1 = (int)cap_h; }
  if ((y1 - y0) > (int)STAR_ROW_MAX) { return -1; }
  for (pass = 0; pass < 3; pass++)
  {
    n = 0U;
    memset(cnt, 0, sizeof(cnt));
    for (y = y0; y < y1; y++)
    {
      float dy = (float)(y - cy);
      s_row_start[y - y0] = (uint16_t)n;
      for (x = cx - (int)r1 - 1; x <= (cx + (int)r1 + 1); x += step)
      {
        float dx = (float)(x - cx);
        float d2 = (dx * dx) + (dy * dy);
        float a;
        int b;
        if ((x < 0) || (x >= (int)cap_w)) { continue; }
        if ((d2 < (r0 * r0)) || (d2 > (r1 * r1))) { continue; }
        a = atan2f(dy, dx);
        if (a < 0.0f) { a += ST_TWO_PI; }
        b = (int)((a * (float)STAR_BINS) / ST_TWO_PI);
        if (b >= (int)STAR_BINS) { b = (int)STAR_BINS - 1; }
        if (n < STAR_TAB_MAX) { s_tab[n] = ((uint32_t)x << 8) | (uint32_t)b; }
        n++;
        cnt[b]++;
      }
    }
    if (n <= STAR_TAB_MAX) { break; }
    step++;
  }
  if (n > STAR_TAB_MAX) { return -1; }
  s_row_start[y1 - y0] = (uint16_t)n;
  for (k = 0; k < (int)STAR_BINS; k++)
  {
    float th = (((float)k + 0.5f) * ST_TWO_PI) / (float)STAR_BINS;
    float a = th * (float)g_star.n_teeth;
    if (cnt[k] == 0U) { return -1; }
    s_cosn[k] = cosf(a);
    s_sinn[k] = sinf(a);
    s_cinv[k] = 1.0f / (float)cnt[k];
  }
  g_star.ann_r0 = (int16_t)(r0 + 0.5f);
  g_star.ann_r1 = (int16_t)r1;
  g_star.tab_n = (uint16_t)n;
  track_reset();
  s_row0 = (uint16_t)y0;
  s_row1 = (uint16_t)y1;
  s_ring_tail = s_ring_head;
  s_gen = (uint8_t)(s_gen + 1U);
  g_star_arm_n++;
  s_tab_on = 1U;
  g_star.armed = 1U;
  return 0;
}

void StarTrack_IsrLine(const uint32_t *src)
{
  uint16_t y = s_line;
  s_line = (uint16_t)(y + 1U);
  if ((s_frame_tab == 0U) || (s_tab_on == 0U) || (y < s_row0) || (y >= s_row1))
  {
    return;
  }
  {
    const uint16_t *px = (const uint16_t *)(const void *)src;
    uint32_t i = s_row_start[y - s_row0];
    uint32_t e = s_row_start[(y - s_row0) + 1U];
    for (; i < e; i++)
    {
      uint32_t en = s_tab[i];
      uint32_t p = px[en >> 8];
      s_acc[en & 0xFFU] += ((p >> 11) & 31U) + ((p >> 5) & 63U) + (p & 31U);
    }
  }
}

void StarTrack_IsrFrame(uint32_t stamp_us, uint16_t lines_expect)
{
  uint16_t nl = s_line;
  uint32_t k;
  s_line = 0U;
  g_star_isr_lines = nl;
  if ((s_frame_tab != 0U) && (s_tab_on != 0U) && (s_frame_gen == s_gen) && (nl == lines_expect))
  {
    float c = 0.0f, s = 0.0f, m = 0.0f, amp;
    for (k = 0U; k < STAR_BINS; k++)
    {
      float v = (float)s_acc[k] * s_cinv[k];
      g_star_prof[k] = (uint16_t)(v * 16.0f);
      m += v;
      c += v * s_cosn[k];
      s += v * s_sinn[k];
    }
    m = m / (float)STAR_BINS;
    amp = (2.0f / (float)STAR_BINS) * sqrtf((c * c) + (s * s));
    {
      uint16_t h = s_ring_head;
      uint16_t nh = (uint16_t)((h + 1U) % STAR_RING);
      if (nh != s_ring_tail)
      {
        s_ring[h].stamp = stamp_us;
        s_ring[h].phase = atan2f(s, c);
        s_ring[h].q = (m > 1.0f) ? (amp / m) : 0.0f;
        s_ring_head = nh;
      }
      else
      {
        g_star_ring_drop++;
      }
    }
    g_star_isr_frames++;
  }
  else if (s_tab_on != 0U)
  {
    g_star_isr_bad++;
    if (nl != lines_expect) { g_star_bad_lines = nl; }
  }
  for (k = 0U; k < STAR_BINS; k++) { s_acc[k] = 0U; }
  s_frame_tab = s_tab_on;
  s_frame_gen = s_gen;
}

/* ======================= 主循环测量 ======================= */

static int32_t iabs32(int32_t v) { return (v < 0) ? -v : v; }

static void meas_record(uint32_t dt_us, double ang_deg, uint8_t laps)
{
  uint8_t i = g_star_meas_i;
  double aa = (ang_deg < 0.0) ? -ang_deg : ang_deg;
  g_star_meas_dt_us[i] = dt_us;
  g_star_meas_ang_mdeg[i] = (int32_t)((aa * 1000.0) + 0.5);
  g_star_meas_dps_e3[i] = (int32_t)(((aa * 1.0e9) / (double)dt_us) + 0.5);
  g_star_meas_laps[i] = laps;
  g_star_seq++;
  if (g_star_seq > 999U) { g_star_seq = 1U; }
  g_star_meas_seq[i] = g_star_seq;
  g_star_meas_i = (uint8_t)((i + 1U) % STAR_MEAS_HIST);
  if (g_star_meas_n < STAR_MEAS_HIST) { g_star_meas_n++; }
  if (g_star_meas_n >= 3U)
  {
    double sum = 0.0, ss = 0.0, mean;
    uint8_t k;
    for (k = 0U; k < g_star_meas_n; k++) { sum += (double)g_star_meas_dps_e3[k]; }
    mean = sum / (double)g_star_meas_n;
    for (k = 0U; k < g_star_meas_n; k++)
    {
      double d = (double)g_star_meas_dps_e3[k] - mean;
      ss += d * d;
    }
    if (mean > 0.0)
    {
      double sd = sqrt(ss / (double)(g_star_meas_n - 1U));
      g_star_rep_e4 = (int32_t)(((sd / mean) * 100.0 * 10000.0) + 0.5);
    }
  }
}

/* 测量窗从这一帧重新起算（首帧或断帧后） */
static void restart_windows(uint32_t stamp)
{
  hist_reset();
  s_lap_t0 = stamp;
  s_lap_a0 = g_star_wheel_deg;
  s_mw_t0 = stamp;
  s_mw_ang = 0.0;
  g_star_mw_laps = 0U;
  g_star_lap_deg = 0.0;
  s_meas_on = 1U;
}

/* 每个有效帧调用：满一整圈（360°）按升针同样的规则决定是否出一行。
 * 圈的终点取第一帧转过 >=360° 的那一帧，角度与时间都按这一帧的实测值。 */
static void lap_step(uint32_t stamp)
{
  double d;
  if (s_meas_on == 0U) { return; }
  d = g_star_wheel_deg - s_lap_a0;
  if (d < 0.0) { d = -d; }
  g_star_lap_deg = d;
  if (d < 360.0) { return; }
  {
    uint32_t lap_dt = stamp - s_lap_t0;
    uint32_t tot;
    uint8_t done = 0U;
    s_mw_ang += d;
    if (g_star_mw_laps < 255U) { g_star_mw_laps++; }
    g_star_lap_us = lap_dt;
    tot = stamp - s_mw_t0;
    /* 梅花轮专用：单圈 >=30 s 跑 1 圈；单圈 <30 s 累加整圈到总时长 >30 s。 */
    if (lap_dt >= MW_TOTAL_US)
    {
      g_star_mw_target = 1U;
      done = 1U;
    }
    else
    {
      g_star_mw_target = 0U;
      if (tot > MW_TOTAL_US) { done = 1U; }
    }
    if (done != 0U)
    {
      meas_record(tot, s_mw_ang, g_star_mw_laps);
      s_mw_t0 = stamp;
      s_mw_ang = 0.0;
      g_star_mw_laps = 0U;
    }
    s_lap_t0 = stamp;
    s_lap_a0 = g_star_wheel_deg;
    g_star_lap_deg = 0.0;
  }
}

int StarTrack_Tick(uint32_t now_us)
{
  while (s_ring_tail != s_ring_head)
  {
    star_evt_t e = s_ring[s_ring_tail];
    s_ring_tail = (uint16_t)((s_ring_tail + 1U) % STAR_RING);
    g_star_last_q = e.q;
    if (e.q < MIN_Q)
    {
      g_star_lowq_n++;
      continue;
    }
    g_star_good_n++;
    s_last_good = e.stamp;
    if (s_have_prev == 0U)
    {
      s_have_prev = 1U;
      s_prev_phase = e.phase;
      s_prev_stamp = e.stamp;
      s_phase0 = e.phase;
      restart_windows(e.stamp);
      s_fps_t0 = e.stamp;
      s_fps_n = 0U;
    }
    else
    {
      uint32_t gap = e.stamp - s_prev_stamp;
      if (gap > GAP_US)
      {
        g_star_gap_n++;
        restart_windows(e.stamp);
      }
      else
      {
        float d = e.phase - s_prev_phase;
        while (d > ST_PI) { d -= ST_TWO_PI; }
        while (d <= -ST_PI) { d += ST_TWO_PI; }
        g_star_accum += (double)d / (double)ST_TWO_PI;
        g_star_wheel_deg = (g_star_accum * 360.0) / (double)g_star.n_teeth;
        lap_step(e.stamp);
      }
      s_prev_phase = e.phase;
      s_prev_stamp = e.stamp;
    }
    g_star_last_phase = e.phase;
    g_star_last_stamp = e.stamp;
    s_hist_t[s_hist_i] = e.stamp;
    s_hist_a[s_hist_i] = g_star_accum;
    s_hist_i = (uint16_t)((s_hist_i + 1U) % STAR_HIST);
    if (s_hist_n < STAR_HIST) { s_hist_n++; }
    s_fps_n++;
    if ((e.stamp - s_fps_t0) >= 1000000U)
    {
      g_star_fps_e1 = (int32_t)((((uint64_t)s_fps_n * 10000000ULL) + ((e.stamp - s_fps_t0) / 2U))
                                / (uint64_t)(e.stamp - s_fps_t0));
      s_fps_t0 = e.stamp;
      s_fps_n = 0U;
    }
    {
      /* 白线（缺口中心参考）的当前角度，画面坐标，0~360° */
      double a = (((double)s_phase0 / (double)ST_TWO_PI) + g_star_accum) * 360.0 / (double)g_star.n_teeth;
      a = fmod(a, 360.0);
      if (a < 0.0) { a += 360.0; }
      g_star_ang_mdeg = (int32_t)(a * 1000.0);
    }
  }
  /* 约 2 s 窗口的实时齿/s */
  if (s_hist_n >= 2U)
  {
    uint16_t newest = (uint16_t)((s_hist_i + STAR_HIST - 1U) % STAR_HIST);
    uint16_t k = (uint16_t)((s_hist_i + STAR_HIST - s_hist_n) % STAR_HIST);
    uint16_t left = s_hist_n;
    while ((left > 2U) && ((s_hist_t[newest] - s_hist_t[k]) > RATE_WIN_US))
    {
      k = (uint16_t)((k + 1U) % STAR_HIST);
      left--;
    }
    if ((s_hist_t[newest] - s_hist_t[k]) >= RATE_MIN_US)
    {
      double d = s_hist_a[newest] - s_hist_a[k];
      double dt = (double)(s_hist_t[newest] - s_hist_t[k]);
      g_star_dir = (d < 0.0) ? -1 : 1;
      if (d < 0.0) { d = -d; }
      g_star_tps_e3 = (int32_t)(((d * 1.0e9) / dt) + 0.5);
      g_star_dps_e3 = (int32_t)(((d * 360.0 * 1.0e9) / (dt * (double)g_star.n_teeth)) + 0.5);
    }
  }
  /* 有符号比较：本次刚消化的帧可能比 now_us 晚一点打戳。 */
  if ((s_tab_on != 0U) && (s_have_prev != 0U) && ((int32_t)(now_us - s_last_good) > (int32_t)LOST_US))
  {
    g_star_lost_n++;
    return 1;
  }
  return 0;
}

