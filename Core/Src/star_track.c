static void fill_rect(uint16_t *fb, int fb_w, int fb_h, int x0, int y0, int x1, int y1, uint16_t c)
{
  int x, y;
  if (x0 < 0) { x0 = 0; }
  if (y0 < 0) { y0 = 0; }
  if (x1 > fb_w) { x1 = fb_w; }
  if (y1 > fb_h) { y1 = fb_h; }
  for (y = y0; y < y1; y++)
  {
    uint16_t *row = fb + (y * fb_w);
    for (x = x0; x < x1; x++) { row[x] = c; }
  }
}

static void plot(uint16_t *fb, int fb_w, int fb_h, int x, int y, uint16_t c, int t, int cx0, int cy0, int cx1, int cy1)
{
  int dx, dy;
  for (dy = -(t / 2); dy <= (t / 2); dy++)
  {
    for (dx = -(t / 2); dx <= (t / 2); dx++)
    {
      int px = x + dx, py = y + dy;
      if ((px < cx0) || (py < cy0) || (px >= cx1) || (py >= cy1)) { continue; }
      if ((px < 0) || (py < 0) || (px >= fb_w) || (py >= fb_h)) { continue; }
      fb[(py * fb_w) + px] = c;
    }
  }
}

static void draw_circle(uint16_t *fb, int fb_w, int fb_h, int cx, int cy, int R, uint16_t c,
                        int t, int stepdeg, int cx0, int cy0, int cx1, int cy1)
{
  int a;
  trig_init();
  for (a = 0; a < 360; a += stepdeg)
  {
    int x = cx + (int)((s_c360[a] * (float)R) + ((s_c360[a] >= 0.0f) ? 0.5f : -0.5f));
    int y = cy + (int)((s_s360[a] * (float)R) + ((s_s360[a] >= 0.0f) ? 0.5f : -0.5f));
    plot(fb, fb_w, fb_h, x, y, c, t, cx0, cy0, cx1, cy1);
  }
}

static void draw_ray(uint16_t *fb, int fb_w, int fb_h, int cx, int cy, float ang, int r0, int r1,
                     uint16_t c, int t, int cx0, int cy0, int cx1, int cy1)
{
  float co = cosf(ang), si = sinf(ang);
  int r;
  for (r = r0; r <= r1; r++)
  {
    int x = cx + (int)((co * (float)r) + ((co >= 0.0f) ? 0.5f : -0.5f));
    int y = cy + (int)((si * (float)r) + ((si >= 0.0f) ? 0.5f : -0.5f));
    plot(fb, fb_w, fb_h, x, y, c, t, cx0, cy0, cx1, cy1);
  }
}

