static const dial_glyph_t *glyph(uint8_t code)
{
  uint32_t i;
  for (i = 0; i < DIAL_FONT_NGLYPH; i++)
  {
    if (dial_font_glyphs[i].code == code) { return &dial_font_glyphs[i]; }
  }
  for (i = 0; i < 6U; i++)
  {
    if (star_extra_glyphs[i].code == code) { return &star_extra_glyphs[i]; }
  }
  for (i = 0; i < 7U; i++)
  {
    if (star_cjk_glyphs[i].code == code) { return &star_cjk_glyphs[i]; }
  }
  return 0;
}

static void blend_px(uint16_t *fb, int fb_w, int fb_h, int x, int y, int a, uint16_t ink)
{
  uint16_t p, out;
  int pr, pg, pb, ir, ig, ib;
  if ((a <= 0) || (x < 0) || (y < 0) || (x >= fb_w) || (y >= fb_h)) { return; }
  if (a > 15) { a = 15; }
  p = fb[(y * fb_w) + x];
  pr = (((p >> 11) & 31) * 255) / 31;
  pg = (((p >> 5) & 63) * 255) / 63;
  pb = ((p & 31) * 255) / 31;
  ir = (((ink >> 11) & 31) * 255) / 31;
  ig = (((ink >> 5) & 63) * 255) / 63;
  ib = ((ink & 31) * 255) / 31;
  pr = ((pr * (15 - a)) + (ir * a)) / 15;
  pg = ((pg * (15 - a)) + (ig * a)) / 15;
  pb = ((pb * (15 - a)) + (ib * a)) / 15;
  out = (uint16_t)(((pr * 31 / 255) << 11) | ((pg * 63 / 255) << 5) | (pb * 31 / 255));
  fb[(y * fb_w) + x] = out;
}

static int draw_code(uint16_t *fb, int fb_w, int fb_h, int x, int y, uint8_t code, uint16_t ink)
{
  const dial_glyph_t *g = glyph(code);
  int ix, iy;
  if (g == 0) { return 8; }
  for (iy = 0; iy < (int)g->h; iy++)
  {
    for (ix = 0; ix < (int)g->w; ix++)
    {
      uint32_t bit_i = (((uint32_t)iy * (uint32_t)g->w) + (uint32_t)ix);
      uint8_t by = g->bits[bit_i / 2U];
      int a = ((bit_i & 1U) == 0U) ? (int)(by & 0x0FU) : (int)(by >> 4);
      if (a != 0) { blend_px(fb, fb_w, fb_h, x + (int)g->xoff + ix, y + (int)g->yoff + iy, a, ink); }
    }
  }
  return (int)((g->adv64 + 32) / 64);
}

static int draw_str_ink(uint16_t *fb, int fb_w, int fb_h, int x, int y, const char *s, uint16_t ink)
{
  int x0 = x;
  if (s == 0) { return 0; }
  while (*s)
  {
    x += draw_code(fb, fb_w, fb_h, x, y, (uint8_t)*s, ink);
    s++;
  }
  return x - x0;
}

static int measure_str(const char *s)
{
  int x = 0;
  if (s == 0) { return 0; }
  while (*s)
  {
    const dial_glyph_t *g = glyph((uint8_t)*s++);
    x += (g != 0) ? (int)((g->adv64 + 32) / 64) : 8;
  }
  return x;
}

static char *put_u(char *p, uint32_t v, int digits)
{
  int i;
  for (i = digits - 1; i >= 0; i--)
  {
    p[i] = (char)('0' + (char)(v % 10U));
    v /= 10U;
  }
  return p + digits;
}

static char *put_uv(char *p, uint32_t v)
{
  char rev[12];
  int k = 0;
  if (v == 0U) { *p++ = '0'; return p; }
  while (v > 0U) { rev[k++] = (char)('0' + (char)(v % 10U)); v /= 10U; }
  while (k > 0) { *p++ = rev[--k]; }
  return p;
}

static char *put_frac(char *p, uint32_t v, uint32_t scale, int frac)
{
  p = put_uv(p, v / scale);
  *p++ = '.';
  return put_u(p, v % scale, frac);
}

static char *put_str(char *p, const char *s)
{
  while (*s) { *p++ = *s++; }
  return p;
}

/* 画一行：最后一个空格之后的部分用蓝字。 */
static void draw_line_split(uint16_t *fb, int fb_w, int fb_h, int x, int y, char *line)
{
  char *sp = 0;
  char *q = line;
  while (*q != 0) { if (*q == ' ') { sp = q; } q++; }
  if (sp == 0)
  {
    (void)draw_str_ink(fb, fb_w, fb_h, x, y, line, TXT_INK);
    return;
  }
  *sp = 0;
  x += draw_str_ink(fb, fb_w, fb_h, x, y, line, TXT_INK);
  x += draw_code(fb, fb_w, fb_h, x, y, (uint8_t)' ', TXT_INK);
  *sp = ' ';
  (void)draw_str_ink(fb, fb_w, fb_h, x, y, sp + 1, TXT_VAL);
}

